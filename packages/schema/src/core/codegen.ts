import * as fs from "node:fs/promises";
import path from "node:path";

import type { RevisionIndex } from "./analysis.js";
import type { Module, Revision } from "./revision.js";
import type { ConstantDefinition, Definition } from "./schema.js";

/** Formats a file's contents. */
type Formatter = (filePath: string, contents: string) => Promise<string>;

/** The most times a file is formatted while waiting for the output to settle. */
const MAX_FORMAT_PASSES = 5;

/*
N.b. Generated code isn't indented, so the first formatting pass wraps nested comments as if they started in the first
column; formatting again wraps them at their final indentation.
*/
async function formatUntilStable(filePath: string, contents: string, format: Formatter): Promise<string> {
  let current = contents;
  for (let pass = 0; pass < MAX_FORMAT_PASSES; pass += 1) {
    // oxlint-disable-next-line no-await-in-loop -- Each pass formats the output of the previous one
    const formatted = await format(filePath, current);
    if (formatted === current) {
      return formatted;
    }
    current = formatted;
  }
  throw new Error(`Formatting ${filePath} didn't settle after ${MAX_FORMAT_PASSES} passes`);
}

/** The first line of every generated file; files starting with it may be overwritten or removed by generators. */
export const GENERATED_HEADER =
  "// This file is generated by scripts/generate.ts from @bachman-dev/wanikani-api-schema; do not edit it by hand.";

/** A file to be generated. */
export interface GeneratedFile {
  /** The file path, relative to the package root, e.g. `src/v20170710/assignments.ts`. */
  readonly path: string;

  /** The file's contents, without the generated header. */
  readonly contents: string;
}

export interface WriteOptions {
  /** The absolute path of the package root. */
  readonly root: string;

  /**
   * Formats a file's contents before it's written.
   *
   * The formatter receives the absolute path of the file and its contents, and returns the formatted contents.
   */
  readonly format: Formatter;
}

/**
 * Writes generated files, then removes previously generated files from the same folders that weren't generated this
 * time. Hand-written files, i.e. those without the generated header, are never removed.
 *
 * @param files The files to write
 * @param options Where and how to write the files
 * @returns The paths of the written and removed files, relative to the package root
 */
export async function writeGeneratedFiles(
  files: readonly GeneratedFile[],
  options: WriteOptions,
): Promise<{ removed: string[]; written: string[] }> {
  const written = new Set<string>();
  const folders = new Set<string>();

  for (const file of files) {
    const filePath = path.join(options.root, file.path);
    // oxlint-disable-next-line no-await-in-loop -- Writing files one at a time keeps the output deterministic
    const contents = await formatUntilStable(filePath, `${GENERATED_HEADER}\n\n${file.contents}`, options.format);
    // oxlint-disable-next-line no-await-in-loop -- See above
    await fs.mkdir(path.dirname(filePath), { recursive: true });
    // oxlint-disable-next-line no-await-in-loop -- See above
    await fs.writeFile(filePath, contents);
    written.add(filePath);
    folders.add(path.dirname(filePath));
  }

  const removed: string[] = [];
  for (const folder of folders) {
    // oxlint-disable-next-line no-await-in-loop -- See above
    const entries = await fs.readdir(folder, { withFileTypes: true });
    for (const entry of entries) {
      const filePath = path.join(folder, entry.name);
      if (entry.isFile() && !written.has(filePath)) {
        // oxlint-disable-next-line no-await-in-loop -- See above
        const contents = await fs.readFile(filePath, "utf8");
        if (contents.startsWith(GENERATED_HEADER)) {
          // oxlint-disable-next-line no-await-in-loop -- See above
          await fs.rm(filePath);
          removed.push(path.relative(options.root, filePath));
        }
      }
    }
  }

  return { removed, written: [...written].map((filePath) => path.relative(options.root, filePath)) };
}

/** Tracks the definitions a generated module uses, so only those from other modules are imported. */
export interface ModuleScope {
  /** The module being generated. */
  readonly module: Module;

  /**
   * Records that a definition is used by the module being generated.
   *
   * @param definition The used definition
   * @returns The definition's name
   */
  use: (definition: ConstantDefinition | Definition) => string;

  /**
   * Lists the used definitions from other modules.
   *
   * @returns The names of the used definitions, grouped by their module
   */
  imports: () => Map<Module, string[]>;
}

/**
 * Creates a scope for generating a module.
 *
 * @param module The module being generated
 * @param index Lookup helpers for the module's revision
 * @returns The module's scope
 */
export function createModuleScope(module: Module, index: RevisionIndex): ModuleScope {
  const used = new Map<Module, Set<string>>();
  return {
    module,
    use: (definition) => {
      const definitionModule = index.moduleOf(definition);
      if (definitionModule !== module) {
        const names = used.get(definitionModule) ?? new Set();
        names.add(definition.name);
        used.set(definitionModule, names);
      }
      return definition.name;
    },
    imports: () => new Map([...used].map(([key, names]) => [key, [...names].toSorted()])),
  };
}

/**
 * Renders a named import statement; the formatter takes care of sorting.
 *
 * @param names The imported names
 * @param from The module specifier
 * @param options Whether to render a type-only import
 * @returns The import statement, or an empty string if there are no names
 */
export function renderImport(names: Iterable<string>, from: string, options: { type?: boolean } = {}): string {
  const sorted = [...new Set(names)].toSorted();
  if (sorted.length === 0) {
    return "";
  }
  return `import ${options.type === true ? "type " : ""}{ ${sorted.join(", ")} } from "${from}";`;
}

/**
 * Joins blocks of code with an empty line between them, skipping empty blocks.
 *
 * @param blocks The blocks of code
 * @returns The joined code, ending with a newline
 */
export function joinBlocks(blocks: Iterable<string>): string {
  return `${[...blocks].filter((block) => block !== "").join("\n\n")}\n`;
}

/**
 * Renders a value as a JavaScript string or number literal.
 *
 * @param value The value
 * @returns The literal
 */
export function renderLiteral(value: boolean | number | string): string {
  return JSON.stringify(value);
}

/**
 * Renders an object key, quoting it if it isn't a valid identifier.
 *
 * @param key The key
 * @returns The key as it should appear in an object literal or type
 */
export function renderKey(key: string): string {
  return /^[A-Za-z_$][\w$]*$/v.test(key) ? key : renderLiteral(key);
}

/** Generates the source files of a package from the schema. */
export interface PackageGenerator {
  /**
   * Generates the file for a module of a revision, e.g. `src/v20170710/assignments.ts`.
   *
   * The generator receives the module, and the revision it's part of.
   */
  readonly module: (module: Module, revision: Revision) => string;

  /** Generates the entrypoint of a revision, e.g. `src/v20170710/index.ts`. */
  readonly revisionIndex: (revision: Revision) => string;

  /** Generates the package entrypoint, `src/index.ts`, which should export the given (latest) revision. */
  readonly rootIndex: (latestRevision: Revision) => string;
}

/**
 * Generates the source files of a package for every revision.
 *
 * @param revisions Every supported revision, oldest first
 * @param generator Generates each file's contents
 * @returns The files to write
 */
export function generatePackageFiles(revisions: readonly Revision[], generator: PackageGenerator): GeneratedFile[] {
  const files: GeneratedFile[] = [];
  for (const revision of revisions) {
    for (const module of revision.modules) {
      files.push({ path: `src/${revision.folder}/${module.name}.ts`, contents: generator.module(module, revision) });
    }
    files.push({ path: `src/${revision.folder}/index.ts`, contents: generator.revisionIndex(revision) });
  }
  const latestRevision = revisions.at(-1);
  if (latestRevision === undefined) {
    throw new Error("There are no revisions to generate");
  }
  files.push({ path: "src/index.ts", contents: generator.rootIndex(latestRevision) });
  return files;
}
